    /// <summary>
    /// 根据 MAC 地址查厂商名。MAC 格式不敏感：支持 "AA:BB:CC:DD:EE:FF"、
    /// "AA-BB-CC-DD-EE-FF"、"AABBCCDDEEFF"。查不到返回 null。
    /// </summary>
    public static string? GetVendor(string? mac)
    {
        if (string.IsNullOrWhiteSpace(mac)) return null;

        // 统一成大写无分隔符
        var clean = mac.ToUpperInvariant().Replace(":", "").Replace("-", "").Replace(" ", "");
        if (clean.Length < 6) return null;

        var oui = clean[..6];
        // 拼成 AA:BB:CC 格式查表
        var key = $"{oui[..2]}:{oui[2..4]}:{oui[4..6]}";
        return Table.TryGetValue(key, out var vendor) ? vendor : null;
    }
